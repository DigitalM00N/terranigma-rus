G = {}


def g(ch, rows, top=0):
    """rows: list of strings, '#' = ink. `top` = first row index."""
    m = [[0] * 16 for _ in range(16)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                m[top + y][x] = 1
    G[ch] = m


