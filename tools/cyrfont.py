"""Cyrillic glyphs for Terranigma's 16x16 2bpp dialogue font.

Glyphs are drawn as black-only masks ('#'); the blue shadow (colour 2) is added
automatically the same way the original font does it (right, down, down-right).
Colour 3 is the transparent background.

Usage:
  python tools/cyrfont.py preview out.png        - render all new glyphs
"""
