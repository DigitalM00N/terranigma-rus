def shaded(mask):
    out = [[1 if mask[y][x] else 3 for x in range(16)] for y in range(16)]
    for y in range(16):
        for x in range(16):
            if mask[y][x]:
                for dx, dy in ((1, 0), (0, 1), (1, 1)):
                    X_, Y_ = x + dx, y + dy
                    if X_ < 16 and Y_ < 16 and out[Y_][X_] == 3:
                        out[Y_][X_] = 2
    return out


def encode(pix):
    """16x16 pixel indices -> 64 bytes: tiles TL, TR, BL, BR, 2bpp planar."""
    out = bytearray()
    for tx, ty in ((0, 0), (8, 0), (0, 8), (8, 8)):
        for y in range(8):
            lo = hi = 0
            for x in range(8):
                v = pix[ty + y][tx + x]
                lo |= (v & 1) << (7 - x)
                hi |= ((v >> 1) & 1) << (7 - x)
            out += bytes((lo, hi))
    return bytes(out)


FONT_BASE = 0x368000  # $B6:8000, 64 bytes per glyph


def apply(rom):
    """Write all new glyphs into a bytearray ROM (original 4MB addressing)."""
    for ch, m in G.items():
        data = encode(shaded(m))
        if ch in RUS2:
            idx = RUS2[ch] & 0x1FF
            off = FONT_BASE + idx * 64
        else:
            off = FONT_BASE + RUS[ch] * 64
        rom[off:off + 64] = data


def preview(path):
    from png import write_png
    chars = sorted(G, key=lambda c: (c.islower(), "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ".find(c.upper())))
    S, cols = 3, 16
    W = cols * 18 * S
    H = ((len(chars) + cols - 1) // cols) * 18 * S
    img = [[4] * W for _ in range(H)]
    for i, ch in enumerate(chars):
        p = shaded(G[ch])
        gx, gy = (i % cols) * 18 * S, (i // cols) * 18 * S
        for y in range(16):
            for x in range(16):
                for a in range(S):
                    for b in range(S):
                        img[gy + y * S + a][gx + x * S + b] = p[y][x]
    write_png(path, W, H, img, [(255, 255, 255), (0, 0, 0), (120, 120, 200), (200, 80, 80), (230, 230, 160)])


